"""
Crisis-detection evaluation: precision / recall / F1 per risk level.

The classifier in api/crisis.py is deterministic and runs before the LLM, so
its recall on genuinely high-risk messages is a hard safety requirement:
a missed high-risk message means a user in crisis gets no helpline.

Run as a test (fails if any high-risk case is missed):
    py -m pytest tests/test_crisis_eval.py -q

Run as a report generator (writes docs/crisis_evaluation.md):
    py tests/test_crisis_eval.py --report
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "api"))

import crisis  # noqa: E402

LEVELS = ["high", "elevated", "none"]
EVAL_PATH = os.path.join(ROOT, "tests", "crisis_eval_set.json")


def load_cases() -> list[dict]:
    with open(EVAL_PATH, encoding="utf-8") as f:
        return json.load(f)["cases"]


def evaluate(cases: list[dict]) -> dict:
    confusion = {t: Counter() for t in LEVELS}   # confusion[true][pred]
    errors = []
    for c in cases:
        pred = crisis.assess(c["text"])
        confusion[c["label"]][pred] += 1
        if pred != c["label"]:
            errors.append({**c, "predicted": pred})

    metrics = {}
    for lvl in LEVELS:
        tp = confusion[lvl][lvl]
        fn = sum(confusion[lvl][p] for p in LEVELS if p != lvl)
        fp = sum(confusion[t][lvl] for t in LEVELS if t != lvl)
        precision = tp / (tp + fp) if tp + fp else 1.0
        recall = tp / (tp + fn) if tp + fn else 1.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        metrics[lvl] = {"tp": tp, "fp": fp, "fn": fn,
                        "precision": precision, "recall": recall, "f1": f1,
                        "support": tp + fn}

    # Safety-critical view: a "high" case predicted as anything else is a miss.
    high_missed = [e for e in errors if e["label"] == "high"]
    # Over-triggering view: a non-high case escalated to "high" interrupts the chat.
    high_false_alarm = [e for e in errors if e["predicted"] == "high"]

    accuracy = sum(confusion[l][l] for l in LEVELS) / len(cases)
    by_group = defaultdict(lambda: [0, 0])
    for c in cases:
        by_group[c["group"]][1] += 1
        if crisis.assess(c["text"]) == c["label"]:
            by_group[c["group"]][0] += 1

    return {
        "n": len(cases),
        "accuracy": accuracy,
        "confusion": confusion,
        "metrics": metrics,
        "errors": errors,
        "high_missed": high_missed,
        "high_false_alarm": high_false_alarm,
        "by_group": dict(by_group),
    }


# --------------------------------------------------------------------------
# pytest entry points
# --------------------------------------------------------------------------
def test_zero_false_negatives_on_high_risk():
    r = evaluate(load_cases())
    missed = [(e["text"], e["predicted"]) for e in r["high_missed"]]
    assert not missed, f"High-risk messages missed: {missed}"


def test_high_precision_floor():
    """Escalating to 'high' replaces the model's reply, so false alarms must stay rare."""
    r = evaluate(load_cases())
    assert r["metrics"]["high"]["precision"] >= 0.90, r["high_false_alarm"]


def test_hard_negatives_not_escalated():
    cases = [c for c in load_cases() if c["group"] == "hard-negative"]
    escalated = [c["text"] for c in cases if crisis.assess(c["text"]) == "high"]
    assert not escalated, f"Everyday phrases escalated to high: {escalated}"


# --------------------------------------------------------------------------
# report generator
# --------------------------------------------------------------------------
def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def render_markdown(r: dict) -> str:
    m = r["metrics"]
    lines = [
        "# Crisis Detection Evaluation",
        "",
        "Generated by `tests/test_crisis_eval.py --report` against `tests/crisis_eval_set.json`.",
        "",
        "## Why this matters",
        "",
        "`api/crisis.py` screens every user message in code before the language model is called. "
        "If it classifies a message as **high**, the app bypasses the model entirely and returns "
        "verified helplines. That makes **recall on high-risk messages** the safety-critical number: "
        "a false negative means someone in crisis gets a normal chatbot reply. "
        "Precision matters too, because a false alarm replaces the model's reply and interrupts the conversation. "
        "The classifier is deliberately tuned for recall first, precision second.",
        "",
        "## Headline numbers",
        "",
        f"- Evaluation set size: **{r['n']}** labelled messages "
        f"({m['high']['support']} high, {m['elevated']['support']} elevated, {m['none']['support']} none)",
        f"- **High-risk recall: {_pct(m['high']['recall'])}** "
        f"({m['high']['fn']} false negatives)",
        f"- High-risk precision: {_pct(m['high']['precision'])} ({m['high']['fp']} false alarms)",
        f"- Overall 3-class accuracy: {_pct(r['accuracy'])}",
        "",
        "## Per-level metrics",
        "",
        "| Level | Support | Precision | Recall | F1 |",
        "|---|---|---|---|---|",
    ]
    for lvl in LEVELS:
        x = m[lvl]
        lines.append(f"| {lvl} | {x['support']} | {_pct(x['precision'])} | {_pct(x['recall'])} | {_pct(x['f1'])} |")

    lines += [
        "",
        "## Baseline before hardening (for comparison)",
        "",
        "The same 101-case set was first run against the original pattern list (2026-09-12) "
        "to find the gaps before any changes were made:",
        "",
        "| Metric | Before | After |",
        "|---|---|---|",
        f"| High-risk recall | 70.7% (12 missed) | {_pct(m['high']['recall'])} ({m['high']['fn']} missed) |",
        f"| High-risk precision | 80.6% (7 false alarms) | {_pct(m['high']['precision'])} ({m['high']['fp']} false alarms) |",
        f"| 3-class accuracy | 74.3% | {_pct(r['accuracy'])} |",
        "",
        "What the baseline missed: passive ideation phrased without the word *die* "
        "(\"better off without me\", \"rather be dead\", \"not worth living\", \"want it all to end\"), "
        "\"do not\" spelled out instead of \"don't\", pill overdoses without the word *overdose*, "
        "and every Hinglish phrasing. What it over-triggered on: \"don't want to live **in** this hostel\", "
        "\"die **of embarrassment**\", \"cut myself **while** chopping\", \"hurt myself **at** the gym\", "
        "\"overdose **on coffee**\". Each of those became a negative-lookahead or a negation rule in `api/crisis.py`.",
    ]

    lines += ["", "## Confusion matrix (rows = true label, columns = predicted)", "",
              "| true \\ pred | high | elevated | none |", "|---|---|---|---|"]
    for t in LEVELS:
        lines.append(f"| **{t}** | " + " | ".join(str(r["confusion"][t][p]) for p in LEVELS) + " |")

    lines += ["", "## Accuracy by case group", "", "| Group | Correct | Total |", "|---|---|---|"]
    for g, (ok, tot) in sorted(r["by_group"].items()):
        lines.append(f"| {g} | {ok} | {tot} |")

    lines += ["", "## Remaining misclassifications", ""]
    if not r["errors"]:
        lines.append("None.")
    else:
        lines += ["| Text | Expected | Predicted | Group |", "|---|---|---|---|"]
        for e in r["errors"]:
            lines.append(f"| {e['text']} | {e['label']} | {e['predicted']} | {e['group']} |")

    lines += [
        "",
        "## How to extend",
        "",
        "1. Add a case to `tests/crisis_eval_set.json` with the *ideal* label.",
        "2. Run `py -m pytest tests/test_crisis_eval.py -q`. The suite fails if any high-risk case is missed "
        "or if high-risk precision drops below 90%.",
        "3. Adjust the patterns in `api/crisis.py`, re-run, then regenerate this file with `--report`.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    r = evaluate(load_cases())
    m = r["metrics"]
    print(f"cases={r['n']}  accuracy={_pct(r['accuracy'])}")
    for lvl in LEVELS:
        x = m[lvl]
        print(f"  {lvl:9s} P={_pct(x['precision']):>6s}  R={_pct(x['recall']):>6s}  "
              f"F1={_pct(x['f1']):>6s}  (tp={x['tp']} fp={x['fp']} fn={x['fn']})")
    if r["errors"]:
        print("\nmisclassified:")
        for e in r["errors"]:
            print(f"  [{e['label']:8s} -> {e['predicted']:8s}] {e['text']}")
    if "--report" in argv:
        out = os.path.join(ROOT, "docs", "crisis_evaluation.md")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            f.write(render_markdown(r))
        print(f"\nwrote {out}")
    return 1 if r["high_missed"] else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
